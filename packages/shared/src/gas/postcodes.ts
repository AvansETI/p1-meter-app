/** Accepts "35", "3511" or "3511 AB"; returns the 2-digit region or null. */
export function postcodeRegion(input: string): string | null {
  const match = /^\s*([1-9]\d)/.exec(input);
  return match && REGIONS[match[1]!] ? match[1]! : null;
}

/** The KNMI station nearest to a postcode region, or undefined for an unknown region. */
export function stationForPostcode(input: string): Station | undefined {
  const region = postcodeRegion(input);
  if (!region) return undefined;
  const [lat, lon] = REGIONS[region]!;
  return nearestStation(lat, lon);
}
